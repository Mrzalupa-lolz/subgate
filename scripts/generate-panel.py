#!/usr/bin/env python3
"""Generate the narrow 3.4.5 users client from the owner's unchanged schema.

The projection retains start/size and the 200 response. ogen v1.24.0 cannot
generate the optional nested filters or same-type error oneOf. These omitted
features remain in the original schema and the hand-written status handler.
"""
import argparse
import copy
import json
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
VERSION = "v1.24.0"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = json.loads((ROOT / "remnawave-openapi.json").read_text())
    operation = source["paths"]["/api/users"]["get"].copy()
    operation["parameters"] = [p for p in operation["parameters"] if p["name"] in ("start", "size")]
    operation["responses"] = {"200": operation["responses"]["200"]}
    subset = {"openapi": source["openapi"], "info": source["info"],
              "paths": {"/api/users": {"get": operation}},
              "components": {"schemas": {}, "securitySchemes": source["components"]["securitySchemes"]}}

    def visit(value):
        if isinstance(value, dict):
            ref = value.get("$ref", "")
            if ref.startswith("#/components/schemas/"):
                name = ref.rsplit("/", 1)[1]
                if name not in subset["components"]["schemas"]:
                    definition = copy.deepcopy(source["components"]["schemas"][name])
                    subset["components"]["schemas"][name] = definition
                    visit(definition)
            for child in value.values():
                visit(child)
        elif isinstance(value, list):
            for child in value:
                visit(child)

    visit(subset["paths"])
    # Tolerant response reader: legacy sparse snapshots omit credentials and
    # unrelated metadata. Core policy fields remain required; every present
    # property retains its original type/format. Numeric id is optional only
    # for the legacy UUID identity accepted by decodeUser.
    user = subset["components"]["schemas"]["GetUsersResponseDto"]["properties"]["response"]["properties"]["users"]["items"]
    user["required"] = ["shortUuid", "username", "status", "trafficLimitBytes", "expireAt", "userTraffic"]
    user["properties"]["userTraffic"]["required"] = ["usedTrafficBytes"]
    destination = ROOT / "core/internal/panel/generated"
    with tempfile.TemporaryDirectory(prefix="subgate-panel-generation-") as temporary:
        temporary = Path(temporary)
        spec = temporary / "panel-users-spec.json"
        spec.write_text(json.dumps(subset, indent=2) + "\n")
        target = temporary / "generated" if args.check else destination
        subprocess.run(["go", "run", f"github.com/ogen-go/ogen/cmd/ogen@{VERSION}",
                        "-config", str(ROOT / "core/internal/panel/ogen.yaml"),
                        "-target", str(target), "-package", "generated", str(spec)],
                       cwd=ROOT, check=True)
        (target / "spec_version.go").write_text(
            "// Code generated by scripts/generate-panel.py; DO NOT EDIT.\n"
            "package generated\n\nconst SpecVersion = " + json.dumps(source["info"]["version"]) + "\n")
        if args.check:
            generated = {p.name: p.read_bytes() for p in target.glob("*.go")}
            checked_in = {p.name: p.read_bytes() for p in destination.glob("*.go")}
            if generated != checked_in:
                raise SystemExit("panel generated code drift: run python3 scripts/generate-panel.py")
            print("Panel generation/spec drift check PASS")


if __name__ == "__main__":
    main()
